#  МОДЕЛИ ДАННЫХ

@dataclass
class Тег:
    """Модель тега - хранит метаданные"""
    идентификатор: int
    имя: str
    пространство_имен: int  # namespace - число
    идентификатор_узла: str  # node_id - строка
    тип_данных: str  # float, int, bool, string


@dataclass
class ЗначениеТега:
    """Модель значения тега"""
    идентификатор_тега: int
    значение: float
    качество: bool = True  # True - данные хорошие, False - плохие
    временная_метка_ms: int = None

    def __post_init__(self):
        if self.временная_метка_ms is None:
            self.временная_метка_ms = int(datetime.now().timestamp() * 1000)


# ПЕРВЫЙ СЕРВИС: ИСТОЧНИК ТЕГОВ

class ИсточникТегов:
    """Генерирует 2000 тегов. Быстрые - каждые 17 мс, обычные - каждые 50 мс"""

    def __init__(self, всего_тегов: int = 2000):
        self.всего_тегов = всего_тегов
        # 30% тегов (около 700) будут быстрыми
        self.быстрые_теги = set(random.sample(range(всего_тегов), всего_тегов // 3))
        self.подписчики = []
        self.прошлые_значения = {}
        self.работает = False

    def подписаться(self, callback):
        """Подписка на получение новых значений"""
        self.подписчики.append(callback)

    async def _сгенерировать_значение(self, идентификатор_тега: int) -> ЗначениеТега:
        """Генерирует случайное значение от 0 до 100"""
        await asyncio.sleep(0)
        значение = round(random.uniform(0, 100), 2)
        return ЗначениеТега(идентификатор_тега=идентификатор_тега, значение=значение)

    async def запустить(self):
        """Запуск генерации тегов"""
        self.работает = True

        async def производитель(интервал_ms: float, список_тегов: Set[int]):
            интервал_сек = интервал_ms / 1000
            while self.работает:
                for идентификатор_тега in список_тегов:
                    if not self.работает:
                        return
                    значение = await self._сгенерировать_значение(идентификатор_тега)

                    # ДЕДУПЛИКАЦИЯ: отправляем только если значение изменилось
                    if self.прошлые_значения.get(идентификатор_тега) != значение.значение:
                        self.прошлые_значения[идентификатор_тега] = значение.значение
                        for подписчик in self.подписчики:
                            await подписчик(значение)

                    await asyncio.sleep(интервал_сек)

        быстрые = self.быстрые_теги
        обычные = set(range(self.всего_тегов)) - быстрые

        print(f"Запуск генерации: {len(быстрые)} быстрых тегов (17 мс), {len(обычные)} обычных (50 мс)")

        # Запускаем два генератора параллельно
        await asyncio.gather(
            производитель(17, быстрые),
            производитель(50, обычные)
        )

    def остановить(self):
        self.работает = False


# БУФЕР С ОГРАНИЧЕНИЕМ РАЗМЕРА

class БуферТегов:
    """Буфер с ограничением размера (queue size)"""

    def __init__(self, максимальный_размер: int = 10000):
        self.очередь = deque(maxlen=максимальный_размер)
        self.максимальный_размер = максимальный_размер

    async def добавить(self, значение: ЗначениеТега):
        """Добавить значение в буфер"""
        self.очередь.append(значение)

    async def взять_пачку(self, размер_пачки: int = 100) -> List[ЗначениеТега]:
        """Взять пачку значений из буфера"""
        пачка = []
        for _ in range(min(размер_пачки, len(self.очередь))):
            пачка.append(self.очередь.popleft())
        return пачка

    def изменить_размер(self, новый_размер: int):
        """Изменить размер очереди (только для админа)"""
        self.максимальный_размер = новый_размер
        self.очередь = deque(self.очередь, maxlen=новый_размер)

    def размер(self) -> int:
        return len(self.очередь)


#  АРХИВАТОР (СОХРАНЕНИЕ В ФАЙЛ)

class АрхиваторTXT:
    """Сохраняет все изменения тегов в текстовый файл"""

    def __init__(self, путь_к_файлу: str = "archive.txt"):
        self.путь_к_файлу = путь_к_файлу
        self.буфер = []
        self.работает = False

    async def запустить(self):
        """Запуск фоновой записи в файл"""
        self.работает = True
        # Создаём файл с заголовком
        with open(self.путь_к_файлу, "w", encoding="utf-8") as файл:
            файл.write("# время, идентификатор_тега, значение, качество\n")

        while self.работает:
            await self._сбросить_буфер()
            await asyncio.sleep(1)

    async def сохранить(self, значение: ЗначениеТега):
        """Добавить значение в архив"""
        время = datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
        строка = f"{время}, {значение.идентификатор_тега}, {значение.значение}, {значение.качество}\n"
        self.буфер.append(строка)

        # Если буфер переполнен - сразу записываем
        if len(self.буфер) >= 100:
            await self._сбросить_буфер()

    async def _сбросить_буфер(self):
        """Записывает буфер в файл"""
        if not self.буфер:
            return
        with open(self.путь_к_файлу, "a", encoding="utf-8") as файл:
            файл.writelines(self.буфер)
        self.буфер.clear()

    def остановить(self):
        self.работает = False


# ВТОРОЙ СЕРВИС: ОТОБРАЖЕНИЕ НА ЭКРАНАХ

class СервисЭкранов:
    """Отображает теги на экранах. На каждом экране 300-500 тегов. Обновление 250 мс"""

    def __init__(self, буфер: БуферТегов):
        self.буфер = буфер
        self.текущие_значения = {}
        self.экраны = {}
        self.очереди_экранов = {}
        self.работает = False

    def добавить_экран(self, идентификатор_экрана: int, список_тегов: List[int]):
        """Добавить новый экран (только админ)"""
        if not (300 <= len(список_тегов) <= 500):
            raise ValueError(f"На экране должно быть 300-500 тегов, получено {len(список_тегов)}")
        self.экраны[идентификатор_экрана] = set(список_тегов)
        self.очереди_экранов[идентификатор_экрана] = []
        print(f"Добавлен экран {идентификатор_экрана} с {len(список_тегов)} тегами")

    def удалить_экран(self, идентификатор_экрана: int):
        """Удалить экран (только админ)"""
        self.экраны.pop(идентификатор_экрана, None)
        self.очереди_экранов.pop(идентификатор_экрана, None)
        print(f"Удалён экран {идентификатор_экрана}")

    def подписаться_на_экран(self, идентификатор_экрана: int, очередь: asyncio.Queue):
        """Подписка на обновления экрана"""
        if идентификатор_экрана in self.очереди_экранов:
            self.очереди_экранов[идентификатор_экрана].append(очередь)

    def отписаться_от_экрана(self, идентификатор_экрана: int, очередь: asyncio.Queue):
        """Отписка от обновлений экрана"""
        if идентификатор_экрана in self.очереди_экранов:
            if очередь in self.очереди_экранов[идентификатор_экрана]:
                self.очереди_экранов[идентификатор_экрана].remove(очередь)

    async def запустить(self):
        """Запуск сервиса отображения"""
        self.работает = True
        while self.работает:
            # Берём новые значения из буфера
            пачка = await self.буфер.взять_пачку(500)

            for значение in пачка:
                self.текущие_значения[значение.идентификатор_тега] = значение.значение

                # Отправляем обновления на все экраны, где есть этот тег
                for идентификатор_экрана, список_тегов in self.экраны.items():
                    if значение.идентификатор_тега in список_тегов:
                        for очередь in self.очереди_экранов.get(идентификатор_экрана, []):
                            try:
                                await очередь.put({значение.идентификатор_тега: значение.значение})
                            except:
                                pass

            await asyncio.sleep(0.25)  # 250 миллисекунд - обновление экранов

    def остановить(self):
        self.работает = False

    def получить_значение_тега(self, идентификатор_тега: int) -> float:
        """Получить текущее значение тега"""
        return self.текущие_значения.get(идентификатор_тега)

    def получить_статистику(self) -> dict:
        """Получить статистику системы"""
        return {
            "всего_тегов": len(self.текущие_значения),
            "активных_экранов": len(self.экраны),
            "список_экранов": list(self.экраны.keys()),
            "тегов_на_экране": {ид: len(теги) for ид, теги in self.экраны.items()}
        }


