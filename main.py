# API ДЛЯ ОПЕРАТОРА (ТОЛЬКО ПРОСМОТР)

app = FastAPI()


@app.get("/api/тег/{идентификатор}")
async def получить_тег(идентификатор: int):
    """Оператор: получить значение тега"""
    значение = сервис_экранов.получить_значение_тега(идентификатор)
    if значение is None:
        raise HTTPException(status_code=404, detail=f"Тег {идентификатор} не найден")
    return {"идентификатор_тега": идентификатор, "значение": значение}


@app.get("/api/экран/{идентификатор_экрана}/поток")
async def смотреть_экран(идентификатор_экрана: int):
    """Оператор: смотреть экран в реальном времени"""
    if идентификатор_экрана not in сервис_экранов.экраны:
        raise HTTPException(status_code=404, detail=f"Экран {идентификатор_экрана} не найден")

    async def поток_данных():
        очередь = asyncio.Queue()
        сервис_экранов.подписаться_на_экран(идентификатор_экрана, очередь)

        try:
            while True:
                данные = await очередь.get()
                yield f"data: {json.dumps(данные)}\n\n"
        except asyncio.CancelledError:
            сервис_экранов.отписаться_от_экрана(идентификатор_экрана, очередь)

    return StreamingResponse(поток_данных(), media_type="text/event-stream")


# API ДЛЯ АДМИНА (МОЖЕТ ВСЁ МЕНЯТЬ)

@app.post("/api/админ/экран/{идентификатор_экрана}")
async def создать_экран(идентификатор_экрана: int, список_тегов: List[int]):
    """Админ: создать новый экран"""
    try:
        сервис_экранов.добавить_экран(идентификатор_экрана, список_тегов)
        return {"статус": "создан", "идентификатор_экрана": идентификатор_экрана, "количество_тегов": len(список_тегов)}
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))


@app.delete("/api/админ/экран/{идентификатор_экрана}")
async def удалить_экран(идентификатор_экрана: int):
    """Админ: удалить экран"""
    сервис_экранов.удалить_экран(идентификатор_экрана)
    return {"статус": "удалён", "идентификатор_экрана": идентификатор_экрана}


@app.put("/api/админ/очередь/размер")
async def изменить_размер_очереди(новый_размер: int):
    """Админ: изменить размер очереди (queue size)"""
    if новый_размер < 1000:
        raise HTTPException(status_code=400, detail="Размер очереди должен быть не менее 1000")
    буфер.изменить_размер(новый_размер)
    return {"статус": "изменён", "новый_размер": новый_размер}


@app.get("/api/админ/статистика")
async def статистика_системы():
    """Админ: посмотреть статистику системы"""
    return сервис_экранов.получить_статистику()


@app.get("/api/админ/очередь/статистика")
async def статистика_очереди():
    """Админ: посмотреть состояние очереди"""
    return {
        "размер_очереди": буфер.размер(),
        "максимальный_размер": буфер.максимальный_размер
    }


